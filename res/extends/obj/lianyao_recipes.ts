// 解析效果文字 "5%气血" → { prop: "hp_per", val: 5 }
function parseEffect(effect) {
    if (!effect) return null;
    // 恢复X%内力 特殊处理（不产生 buff，直接回蓝）
    if (effect.startsWith("恢复")) {
        var m = effect.match(/恢复(\d+)%内力/);
        if (m) return { prop: "recover_mp", val: parseInt(m[1]), isRecover: true };
    }
    var m = effect.match(/^(\d+)%(.+)/);
    if (!m) return null;
    var pct = parseInt(m[1]);
    var name = m[2];
    var prop = EFFECT_PROP[name];
    if (!prop) return null;
    return { prop: prop, val: pct, isPercent: true };
}

// ---- 配方存储 ----
var RECIPES = [];

// 批量添加配方（将 herbs 中文名转为物品路径）
function addRecipes(recipes) {
    for (var i = 0; i < recipes.length; i++) {
        var r = recipes[i];
        var eff = parseEffect(r.effect);
        var ingredients = [];
        for (var j = 0; j < r.herbs.length; j++) {
            var herbName = r.herbs[j];
            if (!herbName) continue;
            var herbPath = HERB_MAP[herbName];
            if (!herbPath) throw new Error("未知炼药材料：" + herbName + "，丹方：" + r.quality + r.name);
            ingredients.push(herbPath);
        }
        RECIPES.push({
            id: r.id,                             // 配方编号 1-115
            name: r.name,                         // 丹药名
            quality: r.quality,                   // 品质文字 "绿色"
            grade: QUALITY_GRADE[r.quality],     // 品质等级 1-5
            effectDesc: r.effect,                 // 效果原文
            effectProp: eff ? eff.prop : null,   // 对应游戏属性名
            effectVal: eff ? eff.val : 0,         // 效果数值
            isRecover: eff ? eff.isRecover : false, // 是否恢复类
            ingredients: ingredients
        });
    }
}

